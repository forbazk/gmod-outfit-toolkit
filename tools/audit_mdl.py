"""Technical audit of a compiled Source model (.mdl/.vvd/.vtx/.phy) and optional .smd files.

Usage: python audit_mdl.py <folder_or_file.mdl> [file.smd ...]
"""
import os
import struct
import sys
from collections import Counter, defaultdict

MDL_FLAGS = {
    0x1: "AUTOGENERATED_HITBOX", 0x2: "USES_ENV_CUBEMAP", 0x4: "FORCE_OPAQUE",
    0x8: "TRANSLUCENT_TWOPASS", 0x10: "STATIC_PROP", 0x20: "USES_FB_TEXTURE",
    0x40: "HASSHADOWLOD", 0x80: "USES_BUMPMAPPING", 0x100: "USE_SHADOWLOD_MATERIALS",
    0x200: "OBSOLETE", 0x400: "UNUSED", 0x800: "NO_FORCED_FADE",
    0x1000: "FORCE_PHONEME_CROSSFADE", 0x2000: "CONSTANT_DIRECTIONAL_LIGHT_DOT",
    0x4000: "FLEXES_CONVERTED", 0x8000: "BUILT_IN_PREVIEW_MODE",
    0x10000: "AMBIENT_BOOST", 0x20000: "DO_NOT_CAST_SHADOWS",
    0x40000: "CAST_TEXTURE_SHADOWS", 0x200000: "VERT_ANIM_FIXED_POINT_SCALE",
}


def cstr(d, off):
    end = d.index(b"\0", off)
    return d[off:end].decode("latin-1")


def i32(d, off):
    return struct.unpack_from("<i", d, off)[0]


def read_mdl(path):
    d = open(path, "rb").read()
    r = {"size": len(d)}
    r["id"], r["version"], r["checksum"] = d[:4].decode(), i32(d, 4), i32(d, 8)
    r["name"] = d[12:76].split(b"\0")[0].decode()
    r["hull"] = struct.unpack_from("<6f", d, 104)
    flags = i32(d, 152)
    r["flags"] = [n for b, n in MDL_FLAGS.items() if flags & b]
    nb, bi = i32(d, 156), i32(d, 160)
    bones = []
    for k in range(nb):
        o = bi + k * 216
        bones.append({"name": cstr(d, o + i32(d, o)), "parent": i32(d, o + 4),
                      "flags": i32(d, o + 160), "proctype": i32(d, o + 164)})
    r["bones"] = bones
    nhs, hsi = i32(d, 172), i32(d, 176)
    r["hitboxsets"] = [(cstr(d, hsi + k * 12 + i32(d, hsi + k * 12)), i32(d, hsi + k * 12 + 4))
                       for k in range(nhs)]
    r["numanims"], r["numseq"] = i32(d, 180), i32(d, 188)
    nt, ti = i32(d, 204), i32(d, 208)
    r["textures"] = [cstr(d, ti + k * 64 + i32(d, ti + k * 64)) for k in range(nt)]
    ncd, cdi = i32(d, 212), i32(d, 216)
    r["cdmaterials"] = [cstr(d, i32(d, cdi + k * 4)) for k in range(ncd)]
    nsr, nsf, si = i32(d, 220), i32(d, 224), i32(d, 228)
    r["skins"] = [list(struct.unpack_from(f"<{nsr}h", d, si + f * nsr * 2)) for f in range(nsf)]
    nbp, bpi = i32(d, 232), i32(d, 236)
    parts = []
    for k in range(nbp):
        o = bpi + k * 16
        name = cstr(d, o + i32(d, o))
        nm, mi = i32(d, o + 4), i32(d, o + 12)
        models = []
        for m in range(nm):
            mo = o + mi + m * 148
            nmesh, mshi, nv = i32(d, mo + 72), i32(d, mo + 76), i32(d, mo + 80)
            meshes = []
            for s in range(nmesh):
                so = mo + mshi + s * 116
                meshes.append({"material": i32(d, so), "numverts": i32(d, so + 8),
                               "numflexes": i32(d, so + 16)})
            models.append({"name": d[mo:mo + 64].split(b"\0")[0].decode("latin-1"),
                           "numverts": nv, "meshes": meshes,
                           "numeyeballs": i32(d, mo + 100)})
        parts.append({"name": name, "models": models})
    r["bodyparts"] = parts
    na, ai = i32(d, 240), i32(d, 244)
    r["attachments"] = [cstr(d, ai + k * 92 + i32(d, ai + k * 92)) for k in range(na)]
    r["numflexdesc"], r["numflexcontrollers"] = i32(d, 260), i32(d, 268)
    r["numikchains"], r["numposeparams"] = i32(d, 284), i32(d, 300)
    r["surfaceprop"] = cstr(d, i32(d, 308))
    r["mass"] = struct.unpack_from("<f", d, 328)[0]
    ninc, inci = i32(d, 336), i32(d, 340)
    r["includemodels"] = [cstr(d, inci + k * 8 + i32(d, inci + k * 8 + 4)) for k in range(ninc)]
    r["rootLOD"], r["numAllowedRootLODs"] = d[377], d[378]
    return r


def read_vvd(path):
    d = open(path, "rb").read()
    nlod = i32(d, 12)
    lodverts = struct.unpack_from("<8i", d, 16)[:nlod]
    nfix, vstart = i32(d, 48), i32(d, 56)
    n = lodverts[0]
    wcount, bone_w = Counter(), defaultdict(float)
    for k in range(n):
        o = vstart + k * 48
        w = struct.unpack_from("<3f", d, o)
        b = d[o + 12:o + 15]
        nbw = d[o + 15]
        wcount[nbw] += 1
        for j in range(nbw):
            bone_w[b[j]] += w[j]
    return {"size": len(d), "numlods": nlod, "lodverts": lodverts, "numfixups": nfix,
            "weights_per_vert": dict(sorted(wcount.items())), "bone_weight": bone_w}


def read_vtx(path):
    d = open(path, "rb").read()
    maxbs, maxbt, maxbv = struct.unpack_from("<HHi", d, 8)
    nlod, nbp = i32(d, 20), i32(d, 28)
    bpo = i32(d, 32)
    lod_tris = []
    strips_groups = 0
    for lod in range(nlod):
        tris = 0
        for b in range(nbp):
            bo = bpo + b * 8
            nm, mo = i32(d, bo), bo + i32(d, bo + 4)
            for m in range(nm):
                mdo = mo + m * 8
                nl, lo = i32(d, mdo), mdo + i32(d, mdo + 4)
                if lod >= nl:
                    continue
                lodo = lo + lod * 12
                nmesh, mesho = i32(d, lodo), lodo + i32(d, lodo + 4)
                for s in range(nmesh):
                    so = mesho + s * 9
                    nsg, sgo = i32(d, so), so + i32(d, so + 4)
                    for g in range(nsg):
                        go = sgo + g * 25
                        tris += i32(d, go + 8) // 3
                        strips_groups += 1
        lod_tris.append(tris)
    return {"size": len(d), "numlods": nlod, "maxBonesPerStrip": maxbs,
            "maxBonesPerTri": maxbt, "maxBonesPerVert": maxbv, "lod_tris": lod_tris,
            "stripgroups_lod0": strips_groups // max(nlod, 1)}


def read_phy(path):
    d = open(path, "rb").read()
    _, _, solids = struct.unpack_from("<iii", d, 0)
    kv = d[d.find(b"solid {"):].decode("latin-1", "replace") if b"solid {" in d else ""
    return {"size": len(d), "solids": solids, "text": kv[:4000]}


def read_smd(path):
    tris_by_mat = Counter()
    verts = set()
    weights_per_vert = Counter()
    bones_used = Counter()
    uv_out = 0
    degenerate = 0
    nodes = {}
    section = None
    mat = None
    tri = []
    with open(path, encoding="latin-1") as f:
        for line in f:
            s = line.strip()
            if not s or s.startswith("//"):
                continue
            if section is None:
                if s in ("nodes", "skeleton", "triangles"):
                    section = s
                continue
            if s == "end":
                section = None
                continue
            if section == "nodes":
                p = s.split('"')
                nodes[int(p[0])] = p[1]
            elif section == "triangles":
                parts = s.split()
                if mat is None:
                    mat = s
                    tri = []
                    continue
                pos = tuple(round(float(x), 4) for x in parts[1:4])
                u, v = float(parts[7]), float(parts[8])
                if u < -0.01 or u > 1.01 or v < -0.01 or v > 1.01:
                    uv_out += 1
                verts.add((pos, parts[7], parts[8]))
                nl = int(parts[9]) if len(parts) > 9 else 0
                weights_per_vert[max(nl, 1)] += 1
                if nl:
                    for j in range(nl):
                        bones_used[int(parts[10 + j * 2])] += 1
                else:
                    bones_used[int(parts[0])] += 1
                tri.append(pos)
                if len(tri) == 3:
                    if len(set(tri)) < 3:
                        degenerate += 1
                    tris_by_mat[mat] += 1
                    mat = None
    return {"nodes": nodes, "tris_by_mat": tris_by_mat, "unique_verts": len(verts),
            "weights_per_vert": dict(sorted(weights_per_vert.items())),
            "bones_used": bones_used, "uv_outside_01": uv_out, "degenerate_tris": degenerate}


def kb(n):
    return f"{n / 1024:,.0f} KB"


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return
    target = args[0]
    if os.path.isdir(target):
        mdls = [os.path.join(target, f) for f in os.listdir(target) if f.endswith(".mdl")]
        smds = [os.path.join(target, f) for f in os.listdir(target) if f.endswith(".smd")]
    else:
        mdls, smds = [target], []
    smds += [a for a in args[1:] if a.endswith(".smd")]

    for mdl in mdls:
        base = mdl[:-4]
        m = read_mdl(mdl)
        print(f"=== MDL {os.path.basename(mdl)} ({kb(m['size'])})")
        print(f"version {m['version']}  internal name: {m['name']}")
        print(f"flags: {', '.join(m['flags']) or '-'}")
        print(f"surfaceprop: {m['surfaceprop']}  mass: {m['mass']:.1f}")
        print(f"includemodels: {m['includemodels']}")
        print(f"anims {m['numanims']} / sequences {m['numseq']}  ik {m['numikchains']}  "
              f"poseparams {m['numposeparams']}  flex {m['numflexdesc']}/{m['numflexcontrollers']}")
        print(f"rootLOD {m['rootLOD']}  allowedRootLODs {m['numAllowedRootLODs']}")
        print(f"cdmaterials: {m['cdmaterials']}")
        print(f"textures ({len(m['textures'])}): {m['textures']}")
        print(f"skins ({len(m['skins'])} families): {m['skins']}")
        for bp in m["bodyparts"]:
            for mo in bp["models"]:
                print(f"bodypart {bp['name']} / {mo['name']}: {mo['numverts']} verts, "
                      f"{len(mo['meshes'])} meshes, eyeballs {mo['numeyeballs']}")
                for me in mo["meshes"]:
                    mat = m["textures"][m["skins"][0][me["material"]]] if m["skins"] else me["material"]
                    print(f"   mesh mat={mat} verts={me['numverts']} flex={me['numflexes']}")
        print(f"hitboxsets: {m['hitboxsets']}")
        print(f"attachments ({len(m['attachments'])}): {m['attachments']}")
        print(f"bones: {len(m['bones'])}")

        vw = {}
        if os.path.exists(base + ".vvd"):
            v = read_vvd(base + ".vvd")
            vw = v["bone_weight"]
            print(f"--- VVD ({kb(v['size'])}) LODs {v['numlods']} verts/LOD {v['lodverts']} "
                  f"fixups {v['numfixups']}")
            print(f"weights per vertex: {v['weights_per_vert']}")
        for ext in (".dx90.vtx", ".dx80.vtx", ".sw.vtx", ".vtx"):
            if os.path.exists(base + ext):
                t = read_vtx(base + ext)
                print(f"--- VTX{ext} ({kb(t['size'])}) LODs {t['numlods']} tris/LOD {t['lod_tris']} "
                      f"stripgroups {t['stripgroups_lod0']} maxBones strip/tri/vert "
                      f"{t['maxBonesPerStrip']}/{t['maxBonesPerTri']}/{t['maxBonesPerVert']}")
        if os.path.exists(base + ".phy"):
            p = read_phy(base + ".phy")
            print(f"--- PHY ({kb(p['size'])}) solids {p['solids']}")
            for line in p["text"].splitlines():
                if '"name"' in line or '"parent"' in line or '"mass"' in line:
                    print("   " + line.strip())
        if vw:
            unused = [b["name"] for k, b in enumerate(m["bones"]) if vw.get(k, 0) == 0]
            print(f"bones without any weight ({len(unused)}): {unused}")
            proc = [b["name"] for b in m["bones"] if b["proctype"]]
            if proc:
                print(f"procedural/jiggle bones: {proc}")

    for smd in smds:
        s = read_smd(smd)
        total = sum(s["tris_by_mat"].values())
        print(f"=== SMD {os.path.basename(smd)}: {total} tris, {s['unique_verts']} unique verts, "
              f"{len(s['nodes'])} nodes")
        for mat, n in s["tris_by_mat"].most_common():
            print(f"   {mat}: {n} tris")
        print(f"weights per vertex: {s['weights_per_vert']}  UV outside 0-1: {s['uv_outside_01']}  "
              f"degenerate tris: {s['degenerate_tris']}")
        unused = [n for k, n in s["nodes"].items() if k not in s["bones_used"]]
        print(f"nodes without weight ({len(unused)}): {unused}")


if __name__ == "__main__":
    main()
